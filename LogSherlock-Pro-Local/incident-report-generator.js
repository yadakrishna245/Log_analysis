(function() {
  'use strict';

  var STYLE_ID = 'lsp-incident-report-style';
  var CSS = '.lsp-incident-report-panel{font-family:-apple-system,BlinkMacSystemFont,"Segoe UI",Roboto,sans-serif;border:1px solid #e0e0e0;border-radius:8px;margin:12px 0;background:#fff;box-shadow:0 2px 8px rgba(0,0,0,0.06)}.lsp-incident-report-header{display:flex;align-items:center;justify-content:space-between;padding:14px 18px;cursor:pointer;background:#f8f9fa;border-radius:8px 8px 0 0;user-select:none}.lsp-incident-report-header h3{margin:0;font-size:16px}.lsp-incident-report-header .toggle{font-size:18px;transition:transform 0.2s}.lsp-incident-report-header .toggle.collapsed{transform:rotate(-90deg)}.lsp-incident-report-body{padding:18px;display:block}.lsp-incident-report-body.hidden{display:none}.lsp-ir-actions{display:flex;gap:8px;flex-wrap:wrap;margin-bottom:16px}.lsp-ir-btn{padding:8px 14px;border:none;border-radius:5px;cursor:pointer;font-size:13px;font-weight:500;transition:background 0.2s}.lsp-ir-btn-generate{background:#4f46e5;color:#fff}.lsp-ir-btn-generate:hover{background:#4338ca}.lsp-ir-btn-copy{background:#10b981;color:#fff}.lsp-ir-btn-copy:hover{background:#059669}.lsp-ir-btn-txt{background:#f59e0b;color:#fff}.lsp-ir-btn-txt:hover{background:#d97706}.lsp-ir-btn-md{background:#8b5cf6;color:#fff}.lsp-ir-btn-md:hover{background:#7c3aed}.lsp-ir-preview{background:#f9fafb;border:1px solid #e5e7eb;border-radius:6px;padding:16px;font-size:13px;line-height:1.6;white-space:pre-wrap;word-wrap:break-word;max-height:500px;overflow-y:auto;font-family:"Cascadia Code","Fira Code",monospace}.lsp-ir-status{margin-top:8px;padding:6px 12px;border-radius:4px;font-size:12px;color:#065f46;background:#d1fae5;display:none}';

  var CATEGORY_RECOMMENDATIONS = {
    storage: 'Suggested: Check disk space, review storage allocation, verify mount points, and inspect I/O performance.',
    network: 'Suggested: Verify network connectivity, check DNS resolution, inspect firewall rules, and review latency metrics.',
    memory: 'Suggested: Investigate memory leaks, review heap usage, check for OOM conditions, and consider scaling resources.',
    auth: 'Suggested: Review authentication logs, check credential expiry, verify access policies, and inspect token validity.',
    service: 'Suggested: Check service health endpoints, review restart counts, inspect dependency availability, and verify configurations.',
    security: 'Suggested: Investigate potential breach vectors, review access logs, check for unauthorized changes, and escalate as needed.',
    performance: 'Suggested: Profile slow operations, review resource utilization, check for bottlenecks, and optimize queries.',
    configuration: 'Suggested: Validate configuration files, check for recent changes, compare against known-good configs.',
    database: 'Suggested: Check connection pools, review query performance, verify replication status, and inspect lock contention.',
    application: 'Suggested: Review application logs, check error rates, inspect recent deployments, and verify dependencies.'
  };

  function countSeverities(findings) {
    var severities = { critical: 0, high: 0, medium: 0, low: 0, info: 0 };
    findings.forEach(function(f) {
      var sev = (f.severity || 'info').toLowerCase();
      if (severities.hasOwnProperty(sev)) { severities[sev]++; } else { severities.info++; }
    });
    return severities;
  }

  function countCategories(findings) {
    var categories = {};
    findings.forEach(function(f) {
      var cat = (f.category || 'unknown').toLowerCase();
      categories[cat] = (categories[cat] || 0) + 1;
    });
    return categories;
  }

  function getTimestamped(findings) {
    return findings.filter(function(f) {
      return f.timestamp && !isNaN(new Date(f.timestamp).getTime());
    }).sort(function(a, b) {
      return new Date(a.timestamp).getTime() - new Date(b.timestamp).getTime();
    });
  }

  function generateReport(findings) {
    var now = new Date();
    var categories = countCategories(findings);
    var severities = countSeverities(findings);
    var topCategory = Object.keys(categories).sort(function(a, b) { return categories[b] - categories[a]; })[0] || 'General';
    var timestamped = getTimestamped(findings);
    var lines = [];

    lines.push('===============================================================');
    lines.push('INCIDENT REPORT');
    lines.push('Generated by LogSherlock Pro \u2014 based on actual scan findings');
    lines.push('===============================================================');
    lines.push('');
    lines.push('TITLE: Log Analysis Incident Report \u2014 ' + topCategory.charAt(0).toUpperCase() + topCategory.slice(1) + ' Issues Detected');
    lines.push('');
    lines.push('DATE/TIME: ' + now.toISOString());

    if (timestamped.length > 0) {
      lines.push('EVENT WINDOW: ' + new Date(timestamped[0].timestamp).toISOString() + ' to ' + new Date(timestamped[timestamped.length - 1].timestamp).toISOString());
    }
    lines.push('TOTAL FINDINGS: ' + findings.length);
    lines.push('');

    lines.push('--- SEVERITY SUMMARY ---');
    Object.keys(severities).forEach(function(sev) {
      if (severities[sev] > 0) lines.push('  ' + sev.toUpperCase() + ': ' + severities[sev]);
    });
    lines.push('');

    lines.push('--- TIMELINE OF EVENTS ---');
    if (timestamped.length === 0) {
      lines.push('  No timestamped events available in findings.');
    } else {
      timestamped.forEach(function(f) {
        lines.push('  [' + new Date(f.timestamp).toISOString() + '] [' + (f.severity || 'info').toUpperCase() + '] ' + f.text);
        if (f.file) lines.push('    File: ' + f.file + (f.line ? ' (line ' + f.line + ')' : ''));
      });
    }
    lines.push('');

    lines.push('--- ROOT CAUSE ANALYSIS ---');
    var criticals = findings.filter(function(f) { return (f.severity || '').toLowerCase() === 'critical'; });
    if (criticals.length > 0 && Object.keys(categories).length > 1) {
      lines.push('  Potential chain detected: ' + criticals.length + ' critical finding(s) across ' + Object.keys(categories).length + ' categories.');
      lines.push('  Categories involved: ' + Object.keys(categories).join(', '));
      lines.push('  Note: Automated correlation \u2014 manual investigation recommended.');
    } else if (criticals.length > 0) {
      lines.push('  ' + criticals.length + ' critical finding(s) in category: ' + topCategory);
    } else {
      lines.push('  No critical-severity chain detected. Findings appear isolated.');
    }
    lines.push('');

    lines.push('--- IMPACT ASSESSMENT ---');
    var impactLevel = severities.critical > 0 ? 'HIGH' : (severities.high > 0 ? 'MEDIUM' : 'LOW');
    lines.push('  Overall Impact Level: ' + impactLevel);
    lines.push('  Affected Categories: ' + Object.keys(categories).join(', '));
    var files = {};
    findings.forEach(function(f) { if (f.file) files[f.file] = true; });
    var fileList = Object.keys(files);
    if (fileList.length > 0) {
      lines.push('  Affected Files (' + fileList.length + '):');
      fileList.forEach(function(fl) { lines.push('    - ' + fl); });
    }
    lines.push('');

    lines.push('--- FINDINGS DETAIL ---');
    findings.forEach(function(f, i) {
      lines.push('  [' + (i + 1) + '] ' + (f.severity || 'info').toUpperCase() + ' | ' + (f.category || 'unknown') + ' | ' + f.text);
      if (f.file) lines.push('      File: ' + f.file + (f.line ? ':' + f.line : ''));
      if (f.context) lines.push('      Context: ' + f.context);
    });
    lines.push('');

    lines.push('--- RECOMMENDED ACTIONS (Suggested) ---');
    Object.keys(categories).forEach(function(cat) {
      var rec = CATEGORY_RECOMMENDATIONS[cat] || 'Suggested: Review findings in "' + cat + '" category and investigate root causes.';
      lines.push('  [' + cat.toUpperCase() + '] ' + rec);
    });
    lines.push('');
    lines.push('===============================================================');
    lines.push('END OF REPORT');

    return lines.join('\n');
  }

  function generateMarkdownReport(findings) {
    var now = new Date();
    var categories = countCategories(findings);
    var severities = countSeverities(findings);
    var topCategory = Object.keys(categories).sort(function(a, b) { return categories[b] - categories[a]; })[0] || 'General';
    var timestamped = getTimestamped(findings);
    var lines = [];

    lines.push('# Incident Report');
    lines.push('');
    lines.push('> Generated by LogSherlock Pro \u2014 based on actual scan findings');
    lines.push('');
    lines.push('## ' + topCategory.charAt(0).toUpperCase() + topCategory.slice(1) + ' Issues Detected');
    lines.push('');
    lines.push('**Date/Time:** ' + now.toISOString());
    lines.push('**Total Findings:** ' + findings.length);
    lines.push('');

    lines.push('## Severity Summary');
    lines.push('| Severity | Count |');
    lines.push('|----------|-------|');
    Object.keys(severities).forEach(function(sev) {
      if (severities[sev] > 0) lines.push('| ' + sev.toUpperCase() + ' | ' + severities[sev] + ' |');
    });
    lines.push('');

    lines.push('## Timeline of Events');
    if (timestamped.length === 0) {
      lines.push('_No timestamped events available._');
    } else {
      timestamped.forEach(function(f) {
        lines.push('- **' + new Date(f.timestamp).toISOString() + '** [`' + (f.severity || 'info').toUpperCase() + '`] ' + f.text);
      });
    }
    lines.push('');

    lines.push('## Findings Detail');
    findings.forEach(function(f, i) {
      lines.push((i + 1) + '. **' + (f.severity || 'info').toUpperCase() + '** | `' + (f.category || 'unknown') + '` | ' + f.text);
      if (f.file) lines.push('   - File: `' + f.file + (f.line ? ':' + f.line : '') + '`');
    });
    lines.push('');

    lines.push('## Recommended Actions (Suggested)');
    Object.keys(categories).forEach(function(cat) {
      var rec = CATEGORY_RECOMMENDATIONS[cat] || 'Review findings in "' + cat + '" category and investigate root causes.';
      lines.push('- **' + cat.toUpperCase() + ':** ' + rec);
    });
    lines.push('');
    lines.push('---');
    lines.push('*End of Report*');

    return lines.join('\n');
  }

  function downloadFile(content, filename, mimeType) {
    var blob = new Blob([content], { type: mimeType });
    var url = URL.createObjectURL(blob);
    var a = document.createElement('a');
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  }

  window.renderIncidentReportPanel = function(findings) {
    findings = findings || [];

    if (!document.getElementById(STYLE_ID)) {
      var style = document.createElement('style');
      style.id = STYLE_ID;
      style.textContent = CSS;
      document.head.appendChild(style);
    }

    var panel = document.createElement('div');
    panel.className = 'lsp-incident-report-panel';

    var header = document.createElement('div');
    header.className = 'lsp-incident-report-header';
    header.innerHTML = '<h3>\uD83D\uDCCB Incident Report Generator</h3><span class="toggle">\u25BC</span>';

    var body = document.createElement('div');
    body.className = 'lsp-incident-report-body';

    var collapsed = false;
    header.addEventListener('click', function() {
      collapsed = !collapsed;
      body.classList.toggle('hidden', collapsed);
      header.querySelector('.toggle').classList.toggle('collapsed', collapsed);
    });

    var actions = document.createElement('div');
    actions.className = 'lsp-ir-actions';

    var btnGenerate = document.createElement('button');
    btnGenerate.className = 'lsp-ir-btn lsp-ir-btn-generate';
    btnGenerate.textContent = '\uD83D\uDCC4 Generate Report';

    var btnCopy = document.createElement('button');
    btnCopy.className = 'lsp-ir-btn lsp-ir-btn-copy';
    btnCopy.textContent = '\uD83D\uDCCB Copy to Clipboard';
    btnCopy.style.display = 'none';

    var btnTxt = document.createElement('button');
    btnTxt.className = 'lsp-ir-btn lsp-ir-btn-txt';
    btnTxt.textContent = '\u2B07 Download .txt';
    btnTxt.style.display = 'none';

    var btnMd = document.createElement('button');
    btnMd.className = 'lsp-ir-btn lsp-ir-btn-md';
    btnMd.textContent = '\u2B07 Download .md';
    btnMd.style.display = 'none';

    actions.appendChild(btnGenerate);
    actions.appendChild(btnCopy);
    actions.appendChild(btnTxt);
    actions.appendChild(btnMd);

    var preview = document.createElement('div');
    preview.className = 'lsp-ir-preview';
    preview.textContent = findings.length > 0
      ? 'Click "Generate Report" to create an incident report from ' + findings.length + ' finding(s).'
      : 'No findings available. Run a scan first to generate a report.';

    var status = document.createElement('div');
    status.className = 'lsp-ir-status';

    function showStatus(msg) {
      status.textContent = msg;
      status.style.display = 'block';
      setTimeout(function() { status.style.display = 'none'; }, 3000);
    }

    var currentReport = '';
    var currentMdReport = '';

    btnGenerate.addEventListener('click', function() {
      if (findings.length === 0) { preview.textContent = 'No findings to report.'; return; }
      currentReport = generateReport(findings);
      currentMdReport = generateMarkdownReport(findings);
      preview.textContent = currentReport;
      btnCopy.style.display = 'inline-block';
      btnTxt.style.display = 'inline-block';
      btnMd.style.display = 'inline-block';
      showStatus('Report generated successfully.');
    });

    btnCopy.addEventListener('click', function() {
      if (!currentReport) return;
      navigator.clipboard.writeText(currentReport).then(function() {
        showStatus('Copied to clipboard!');
      }).catch(function() { showStatus('Copy failed \u2014 use Download instead.'); });
    });

    btnTxt.addEventListener('click', function() {
      if (!currentReport) return;
      downloadFile(currentReport, 'incident-report-' + new Date().toISOString().replace(/[:.]/g, '-') + '.txt', 'text/plain');
      showStatus('Downloaded as .txt');
    });

    btnMd.addEventListener('click', function() {
      if (!currentMdReport) return;
      downloadFile(currentMdReport, 'incident-report-' + new Date().toISOString().replace(/[:.]/g, '-') + '.md', 'text/markdown');
      showStatus('Downloaded as .md');
    });

    body.appendChild(actions);
    body.appendChild(preview);
    body.appendChild(status);
    panel.appendChild(header);
    panel.appendChild(body);

    return panel;
  };
})();
